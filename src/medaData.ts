export const AVAILABLE_SOLS = [10, 14, 20, 28] as const;

export function getMedaWeather(sol: number, hour: number): { airC: number; groundC: number; source: "OBSERVED" | "MODELED" } {
  const readings = MEDA_SOLS[sol] ?? MEDA_SOLS[20];
  const r = readings[Math.floor(hour) % 24];
  if (r && r.airC !== null && r.groundC !== null) {
    return { airC: r.airC, groundC: r.groundC, source: "OBSERVED" };
  }
  // Diurnal sinusoidal model calibrated to Jezero Crater MEDA baseline
  const rad = ((hour - 13) / 24) * 2 * Math.PI;
  const groundC = Math.round((-35 + 40 * Math.cos(rad)) * 10) / 10;
  const airRad = ((hour - 14) / 24) * 2 * Math.PI;
  const airC = Math.round((-40 + 28 * Math.cos(airRad)) * 10) / 10;
  return { airC, groundC, source: "MODELED" };
}

export function solHourToSun(hour: number): { sunEl: number; sunAz: number; isNight: boolean } {
  const h = Math.max(0, Math.min(23.99, hour));
  const isNight = h < 6 || h >= 18;
  if (isNight) {
    // Nocturnal / twilight ambient
    const az = (h < 6 ? 90 - (6 - h) * 15 : 270 + (h - 18) * 15 + 360) % 360;
    return { sunEl: 4, sunAz: az, isNight: true };
  }
  const frac = (h - 6) / 12;
  const sunEl = Math.round(Math.sin(frac * Math.PI) * 58 + 4);
  const sunAz = Math.round(90 + frac * 180);
  return { sunEl, sunAz, isNight: false };
}


#!/usr/bin/env python3
"""Build web-ready terrain from the HiRISE DTM (stdlib only).
Outputs: public/jezero-dem.bin (Int16 decimetres, 480x304, big window) and src/jezeroGrid.ts (120x76 planning grid)."""
import sys, os, json, base64, struct, math
sys.path.insert(0, os.path.dirname(__file__))
from tiff_read import read_ifds, read_level
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
d = open(os.path.join(ROOT, 'data/raw/D3/DTEEC_045994_1985_046060_1985_U01.tif'), 'rb').read()
ifds = read_ifds(d); base = ifds[0]
lvl = ifds[2]  # 1716 x 3543
step_m = base['scale'][0] * base['w'][0] / lvl['w'][0]
rows = read_level(d, lvl); H, W = len(rows), len(rows[0])
print('level', W, H, 'm/px', round(step_m, 3))
OW, OH = 480, 304                      # output samples
# window in level pixels: keep 120:76 aspect; search for the most varied nodata-free window
ww = int(W * 0.62); wh = round(ww * 76 / 120)
best = None
for y0 in range(0, H - wh, 40):
  for x0 in range(0, W - ww, 40):
    vals = []; bad = 0
    for y in range(y0, y0 + wh, 8):
        r = rows[y]
        for x in range(x0, x0 + ww, 8):
            v = r[x]
            if v is None: bad += 1
            else: vals.append(v)
    if bad or not vals: continue
    m = sum(vals) / len(vals); sd = math.sqrt(sum((v - m) ** 2 for v in vals) / len(vals))
    if best is None or sd > best[0]: best = (sd, y0, x0)
print('best window y0', best)
y0, x0 = best[1], best[2]
def sample(fx, fy):  # bilinear in level space
    x = x0 + fx * (ww - 1); y = y0 + fy * (wh - 1); xi, yi = int(x), int(y); tx, ty = x - xi, y - yi
    def g(a, b):
        v = rows[min(H - 1, b)][min(W - 1, a)]
        return v
    q = [g(xi, yi), g(xi + 1, yi), g(xi, yi + 1), g(xi + 1, yi + 1)]
    ok = [v for v in q if v is not None]
    if not ok: return None
    q = [v if v is not None else sum(ok) / len(ok) for v in q]
    return (q[0] * (1 - tx) + q[1] * tx) * (1 - ty) + (q[2] * (1 - tx) + q[3] * tx) * ty
hi = [[sample(x / (OW - 1), y / (OH - 1)) for x in range(OW)] for y in range(OH)]
flat = [v for r in hi for v in r if v is not None]; mean = sum(flat) / len(flat)
hi = [[mean if v is None else v for v in r] for r in hi]
mn = min(min(r) for r in hi); mx = max(max(r) for r in hi)
print('elev', round(mn, 1), round(mx, 1))
with open(os.path.join(ROOT, 'public/jezero-dem.bin'), 'wb') as f:
    f.write(struct.pack('<'+str(OW*OH)+'h', *[round(v * 10) for r in hi for v in r]))
# 120x76 planning grid = 4x4 block mean
gw, gh = 120, 76
grid = [[sum(hi[y*4+j][x*4+i] for j in range(4) for i in range(4)) / 16 for x in range(gw)] for y in range(gh)]
win_w_m = step_m * (ww - 1)
meta = dict(w=gw, h=gh, cellM=round(win_w_m / gw, 2), widthM=round(win_w_m, 1), heightM=round(step_m * (wh - 1), 1), min=round(mn, 1), max=round(mx, 1), hiW=OW, hiH=OH)
b64 = base64.b64encode(struct.pack('<'+str(gw*gh)+'h', *[round(v * 10) for r in grid for v in r])).decode()
open(os.path.join(ROOT, 'src/jezeroGrid.ts'), 'w').write(
    "// GENERATED by data/build_dem.py from the USGS HiRISE DTM DTEEC_045994_1985_046060_1985_U01 (DERIVED, CC0).\n"
    "// Int16 decimetres, row-major, 4x4 block mean of the render grid.\n"
    f"export const JEZERO_META = {json.dumps(meta)} as const;\nexport const JEZERO_B64 = \"{b64}\";\n")
json.dump(meta, open(os.path.join(ROOT, 'public/jezero-dem.json'), 'w'))
print(meta)
